/**
 * Convert ISO-2 country code to native country flag emoji.
 * e.g., 'US' -> 🇺🇸, 'NG' -> 🇳🇬, 'GB' -> 🇬🇧, 'SA' -> 🇸🇦, 'AE' -> 🇦🇪
 */
export const getFlagEmoji = (countryCode) => {
  if (!countryCode || countryCode === 'OTHER') return '🌐';
  try {
    const codePoints = countryCode
      .toUpperCase()
      .split('')
      .map(char => 127397 + char.charCodeAt());
    return String.fromCodePoint(...codePoints);
  } catch (e) {
    return '🌐';
  }
};

export const getCountryByDialCode = (code) => {
  return countriesData.find(c => c.dialCode === code) || countriesData[0];
};

export const getCountryByName = (name) => {
  return countriesData.find(c => c.name.toLowerCase() === (name || '').toLowerCase()) || countriesData[0];
};

export const getCountryByIso = (iso) => {
  return countriesData.find(c => c.iso.toUpperCase() === (iso || '').toUpperCase()) || countriesData[0];
};
